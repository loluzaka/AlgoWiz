#ifndef REPORTEXPORTER_H
#define REPORTEXPORTER_H

// Execution Summary Export: writes summary_report.md (valid GitHub-flavoured Markdown) for a
// lab submission. Uses std::ofstream only, so the engine stays free of Qt (decision recorded
// in STRUCTURE.txt). The optional PNG export of the Qt plan is not implemented: the terminal
// version has no bitmap canvas; the report instead embeds a plain-text snapshot of the picture.

#include <cstdio>
#include <ctime>
#include <fstream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

#include "../Algorithm.h"
#include "../Describe.h"
#include "../ExecutionEngine.h"
#include "../race/RaceController.h"

using namespace std;

struct ReportData {
    const AlgorithmInfo* info = nullptr;
    const Timeline* timeline = nullptr;
    string snapshot;                       // optional plain-text picture of the final state
    vector<ComparisonRow> comparison;      // optional: filled by Race Mode
    size_t maxStepRows = 100;              // the step log is truncated after this many rows
};

class ReportExporter {
public:
    static string escapeCell(const string& s) {
        string r;
        for (char c : s) { if (c == '|') r += "\\|"; else if (c == '\n') r += ' '; else r += c; }
        return r;
    }

    static string render(const ReportData& d) {
        ostringstream o;
        const AlgorithmInfo& info = *d.info;
        const Timeline& tl = *d.timeline;
        ExecutionEngine e;
        e.load(tl);
        const Statistics& st = e.finalStats();

        time_t now = time(nullptr);
        char when[64];
        strftime(when, sizeof when, "%Y-%m-%d %H:%M:%S", localtime(&now));

        o << "# Execution Summary - " << info.name << "\n\n";
        o << "*Generated by Algo Visualizer on " << when << "*\n\n";
        o << "## 1. Algorithm\n\n";
        o << "| Property | Value |\n|---|---|\n";
        o << "| Name | " << escapeCell(info.name) << " |\n| Category | " << escapeCell(info.category) << " |\n";
        o << "| Best case | " << escapeCell(info.best) << " |\n| Average case | " << escapeCell(info.average) << " |\n";
        o << "| Worst case | " << escapeCell(info.worst) << " |\n| Space | " << escapeCell(info.space) << " |\n\n";
        if (!info.description.empty()) o << info.description << "\n\n";

        o << "## 2. Input\n\n" << (tl.inputDescription.empty() ? "(not recorded)" : tl.inputDescription) << "\n\n";

        o << "## 3. Execution\n\n";
        o << "| Metric | Value |\n|---|---|\n| Recorded steps | " << tl.steps.size() << " |\n";
        char ms[32];
        snprintf(ms, sizeof ms, "%.3f", tl.runtimeMs);
        o << "| Time to record the steps | " << ms << " ms |\n";
        for (const auto& r : st.rows()) o << "| " << r.first << " | " << r.second << " |\n";
        o << "\n";
        if (!tl.error.empty()) o << "**The run was rejected:** " << tl.error << "\n\n";

        o << "## 4. Operation histogram\n\n| Operation | Count |\n|---|---|\n";
        map<string, int> hist;
        for (const Step& s : tl.steps) hist[opName(s.op)]++;
        for (const auto& h : hist) o << "| " << h.first << " | " << h.second << " |\n";
        if (hist.empty()) o << "| (no steps) | 0 |\n";
        o << "\n";

        o << "## 5. Theory versus measurement\n\n";
        WorldState w0 = e.stateAt(0);
        const Container* c = w0.find(0);
        int n = c ? (int)max<size_t>(c->nodes.size(), (size_t)max(0, c->capacity)) : 0;
        o << "The input holds **n = " << n << "** element(s). The algorithm is documented as " << info.average << " on average and "
          << info.worst << " in the worst case; this run performed " << st.comparisons << " comparison(s), " << st.swaps << " swap(s) and "
          << st.assignments << " assignment(s).\n\n";

        if (!d.comparison.empty()) {
            o << "## 6. Comparison with another algorithm\n\n```\n" << comparisonTable(d.comparison) << "```\n\n";
        }

        if (!d.snapshot.empty()) o << "## Final picture\n\n```\n" << d.snapshot << "```\n\n";

        o << "## Step log\n\n| # | Operation | Explanation |\n|---|---|---|\n";
        size_t shown = min(tl.steps.size(), d.maxStepRows);
        for (size_t i = 0; i < shown; i++)
            o << "| " << (i + 1) << " | " << escapeCell(describeStep(tl.steps[i])) << " | " << escapeCell(tl.steps[i].note) << " |\n";
        if (tl.steps.size() > shown) o << "\n*... " << (tl.steps.size() - shown) << " more step(s) not shown.*\n";
        return o.str();
    }

    // Returns "" on success or an error message.
    static string write(const string& path, const ReportData& d) {
        if (!d.info || !d.timeline) return "Nothing to export: no algorithm has been run yet.";
        ofstream f(path);
        if (!f) return "Could not open \"" + path + "\" for writing.";
        f << render(d);
        f.close();
        return f.fail() ? "Writing \"" + path + "\" failed." : "";
    }
};

#endif
